import jax
import jax.numpy as jnp
from flax import nnx

from models.phys_vae import PhysVAE
from utils.misc import Distribution


def KL_divergence(
    p_mean: jax.Array, p_log_var: jax.Array, q_mean: jax.Array, q_log_var: jax.Array
) -> jax.Array:
    """
     Calculate the KL divergence between two normal distributions parameterised by the provided distribution statistics.
     In particular this calculates D_KL(p || q).

     Parameters
     ----------
     p_mean : jax.Array
         The mean statistic for the p distribution
     p_log_var : jax.Array
         The log variance statistic for the p distribution
     q_mean : jax.Array
         The mean statistic for the q distribution
     q_log_var : jax.Array
         The log variance statistic for the q distribution

     Return
    ------
     KL_divergence : jax.Array
         The KL divergence between the estimate and it's prior
    """
    return 0.5 * jnp.sum(
        jnp.exp(p_log_var - q_log_var)
        - 1.0
        + q_log_var
        - p_log_var
        + jnp.pow((q_mean - p_mean), 2) / jnp.exp(q_log_var),
        axis=1,
    )


def ELBO_reconstruction_loss(
    x: jax.Array,
    x_stat: Distribution,
    phys_stats: list[Distribution],
    aux_stats: list[Distribution],
    phys_priors: list[Distribution],
    aux_priors: list[Distribution],
) -> tuple[jax.Array, jax.Array]:
    """
    Calculates the ELBO and reconstruction loss for a given model and datapoint.
    This is the standard VAE training loss without the physics grounding.

    Parameters
    ----------
    x : Array (B, T)
        The datapoint to evaluate on where B is the batch and T the timesteps
    x_stat : Distribution (m, B, T)
        The generated distribution statistics where m is the function combinations, B the batch and T the timesteps
    phys_stats : Distribution
        The generated physics latent stats
    aux_stats : Distribution
        The generated auxiliary latent stats
    phys_priors : Distribution
        The prior physics latent stats
    aux_priors : Distribution
        The prior auxiliary latent stats

    Returns
    -------
    recon_loss : Array
        The mean reconstruction loss of the model across the datapoints
    ELBO_loss : Array
        The mean ELBO of the model across the datapoints
    """
    # Calculate ELBO
    kldiv = jnp.zeros_like(x)[:, 0]
    for stat, prior in zip(phys_stats, phys_priors):
        kldiv += KL_divergence(stat[0], stat[1], prior[0], prior[1])

    for stat, prior in zip(aux_stats, aux_priors):
        kldiv += KL_divergence(stat[0], stat[1], prior[0], prior[1])

    # Only carry out on full run so last entry in x_stat
    # x_stat : (m, B, T), x : (B, T)
    reconstruction_err = jnp.pow(x_stat[0][-1, :, :] - x, 2).sum(axis=1).mean()

    # Calculate negative ELBO
    return reconstruction_err, kldiv.mean()


def physics_only_loss(enc_phys_only: jax.Array, dec_phys_only: jax.Array) -> jax.Array:
    """
    Regularise the physics only estimation to match the known ODE/PDE.
    This constrains the model to correctly estimate what is known physics and what is not.

    Parameters
    ----------
    enc_phys_only : jax.Array
        The estimated known physics by the encoder
    dec_phys_only : jax.Array
        The actual known physics generated by the decoder

    Return
    ------
    loss : jax.Array
        The mean stop-gradient reconstruction loss of the estimate
    """
    return (
        jnp.pow(enc_phys_only - jax.lax.stop_gradient(dec_phys_only), 2)
        .sum(axis=1)
        .mean()
    )


def augmentation_loss(
    model: PhysVAE, phys_params: list[jax.Array], y_init: jax.Array, key: jax.Array
) -> jax.Array:
    """
    Augment the known physics parameters and train the physics latent estimation.
    This constrains the model to correctly estimate known physics parameters, assuming it can correctly disintangle the data into known physics and auxiliary information.

    Parameters
    ----------
    model : PhysVAE
        The model being trained
    phys_params : list[Array]
        The physics latents
    y_init : jax.Array
        The initial condition
    key : PRNG
        The random key

    Return
    loss : jax.Array
        The data augmentation loss
    """
    model.eval()
    aug_params = []
    for aug_param in phys_params:
        key, aug_key = jax.random.split(key, 2)
        aug_param = jax.lax.stop_gradient(
            (
                jax.random.randint(aug_key, aug_param.shape, 0, 1000)
                * (3.14 - 0.785)
                / 1000
            )
            + 0.785
        )
        aug_params.append(aug_param)

    aug_x_mean = jax.lax.stop_gradient(
        model.generate_physics(aug_params, jax.lax.stop_gradient(y_init))
    )

    model.train()
    aug_loss = jnp.zeros(())
    for phys_func, aug_param in zip(model.encode.phys_funcs, aug_params):
        aug_loss += jnp.pow(phys_func(aug_x_mean) - aug_param, 2).sum(axis=1).mean()

    return aug_loss


def discrepancy_loss(x_stats: Distribution, mask: jax.Array) -> jax.Array:
    """
    Reduce the marginal discrepancy between the physics model and the models auxiliary functions.
    This prevents the model from ignoring the provided physics model.

    Parameters
    ----------
    x_stats : Distribution
        The models predicted output statistics
    mask : Array (m-1, m-1)
        The discrepancy mask

    Returns
    -------
    loss : Array
        The discrepancy loss
    """
    # x_stats : (m, B, T)

    # Calculate discrepancy matrix
    # divergences : (m - 1, m - 1, B)
    divergences = jax.vmap(
        lambda mu_p, sigma_p: jax.vmap(
            lambda mu_q, sigma_q: KL_divergence(mu_p, sigma_p, mu_q, sigma_q),
            in_axes=(0, 0),
            out_axes=0,
        )(x_stats[0][:-1, :, :], x_stats[1][:-1, :, :]),
        in_axes=(0, 0),
        out_axes=0,
    )(x_stats[0][1:, :, :], x_stats[1][1:, :, :])

    masked_divs = divergences.mean(axis=2) * mask

    # Weighted sum
    return masked_divs.sum() / mask.sum()


def loss_fn(model: PhysVAE, data: jax.Array, key: jax.Array) -> jax.Array:
    """
    Container function for the separated losses described in Takeishi & Kalousis.

    Parameters
    ----------
    model : PhysVAE
        The model to train
    data : Array
        The datapoint to calculate the loss on
    key : PRNG
        The random key to use

    Returns
    -------
    loss : jax.Array
        The total loss of the model on the data
    """
    # Encode batch
    phys_stats, aux_stats, phys_only = model.encode(data)

    # Get priors
    phys_priors, aux_priors = model.priors(data.shape[0])

    # Generate a batched samples
    key, sample_key = jax.random.split(key, 2)
    phys_latents, aux_latents = model.sample_latents(phys_stats, aux_stats, sample_key)

    # Decode samples
    init_y = data[:, 0].reshape(-1, 1)
    # x_stat : (m, B, T)
    x_stat = model.decode(phys_latents, aux_latents, init_y, train=True)

    # Standard error
    rec_err, kldiv = ELBO_reconstruction_loss(
        data, x_stat, phys_stats, aux_stats, phys_priors, aux_priors
    )

    # Physics latent grounding
    # first entry in x_stat is the physics only generation
    phys_loss = physics_only_loss(phys_only, x_stat[0][0, :, :])

    # Decoder grounding
    key, aug_key = jax.random.split(key, 2)
    data_aug_loss = augmentation_loss(model, phys_latents, init_y, aug_key)

    # Discrepancy loss
    disc_loss = discrepancy_loss(x_stat, model.mask)

    return (
        rec_err
        + kldiv
        + (model.alpha * disc_loss)
        + (model.beta * phys_loss)
        + (model.gamma * data_aug_loss)
    )


@nnx.jit
def train_step(
    model: nnx.Module, data: jax.Array, optimizer: nnx.Optimizer, key: jax.Array
):
    """
    Carry out a single VAE train step

    Parameters
    ----------
    model : PhysVAE
        The model to train
    data : Array
        The datapoint
    optimizer : Optimizer
        The optimizer for the models parameters
    key : Array
        PRNG key
    output_dist : str = bernoulli
        The distribution to use for the output
    """
    if not isinstance(model, PhysVAE):
        raise TypeError(f"Expected model to be type PhysVAE not {type(model)}")

    loss, grads = nnx.value_and_grad(loss_fn)(model, data, key)
    optimizer.update(model, grads)
    return loss
